    complete_area = Polygon([
        # Main room
        (0, 0),
        (40, 0),

        # Narrow right exit
        (40, 8),
        (46, 8),
        (46, 10),
        (40, 10),

        # Upper-right part of the room
        (40, 30),

        # Wide upper exit
        (25, 30),
        (25, 36),
        (15, 36),
        (15, 30),

        # Upper-left part of the room
        (0, 30),
    ])

    obstacles = []

    waypoints = {
        "1": ([5.0, 5.0], 2.5),
        "2": ([15.0, 5.0], 2.5),
        "3": ([25.0, 5.0], 2.5),

        "4": ([5.0, 15.0], 2.5),
        "5": ([15.0, 15.0], 2.5),
        "6": ([25.0, 15.0], 2.5),

        "7": ([5.0, 25.0], 2.5),
        "8": ([15.0, 25.0], 2.5),
        "9": ([25.0, 25.0], 2.5),

        "10": ([35.0, 5.0], 2.5),
        "11": ([35.0, 15.0], 2.5),
        "12": ([35.0, 25.0], 2.5),

        "13": ([18.0, 33.0], 1.5),
        "14": ([23.0, 32.0], 1.0),

        "15": ([41.0, 9.0], 0.5),
        "16": ([43.0, 9.0], 0.5),
        "17": ([45.0, 9.0], 0.5),

        # Combined upper exit area
        "18": ([23.0, 35.0], 1.0),
    }

    G = nx.DiGraph()

    for node, _ in waypoints.items():
        G.add_node(node, risk=0.0, blocked=False, is_stairs=False, floor=0)

    edges = [
        # Main room grid connections
        ("1", "2", 10.0, 100),
        ("2", "1", 10.0, 100),
        ("2", "3", 10.0, 100),
        ("3", "2", 10.0, 100),

        ("4", "5", 10.0, 100),
        ("5", "4", 10.0, 100),
        ("5", "6", 10.0, 100),
        ("6", "5", 10.0, 100),

        ("7", "8", 10.0, 100),
        ("8", "7", 10.0, 100),
        ("8", "9", 10.0, 100),
        ("9", "8", 10.0, 100),

        ("1", "4", 10.0, 100),
        ("4", "1", 10.0, 100),
        ("4", "7", 10.0, 100),
        ("7", "4", 10.0, 100),

        ("2", "5", 10.0, 100),
        ("5", "2", 10.0, 100),
        ("5", "8", 10.0, 100),
        ("8", "5", 10.0, 100),

        ("3", "6", 10.0, 100),
        ("6", "3", 10.0, 100),
        ("6", "9", 10.0, 100),
        ("9", "6", 10.0, 100),

        # Connections from the main room to adjacent areas
        ("3", "10", 10.0, 100),
        ("10", "3", 10.0, 100),

        ("6", "11", 10.0, 100),
        ("11", "6", 10.0, 100),

        ("9", "12", 10.0, 100),
        ("12", "9", 10.0, 100),

        ("8", "13", 8.54400374531753, 36),
        ("13", "8", 8.54400374531753, 36),

        ("9", "14", 7.280109889280518, 16),
        ("14", "9", 7.280109889280518, 16),

        # Right-side corridor connections
        ("10", "15", 7.211102550927978, 4),
        ("15", "10", 7.211102550927978, 4),

        ("10", "11", 10.0, 100),
        ("11", "10", 10.0, 100),

        ("11", "12", 10.0, 100),
        ("12", "11", 10.0, 100),

        # Upper exit connections
        ("13", "14", 5.0990195135927845, 16),
        ("14", "13", 5.0990195135927845, 16),

        ("13", "18", 5.385164807134504, 8),
        ("18", "13", 5.385164807134504, 8),

        ("14", "18", 3.0, 8),
        ("18", "14", 3.0, 8),

        # Narrow right exit connections
        ("15", "16", 2.0, 4),
        ("16", "15", 2.0, 4),

        ("16", "17", 2.0, 4),
        ("17", "16", 2.0, 4),
    ]

    add_edges_with_capacity(G, edges)

    specific_areas = {
        # Main room divided into a 3x3 grid
        "1": Polygon([(0, 0), (10, 0), (10, 10), (0, 10)]),
        "2": Polygon([(10, 0), (20, 0), (20, 10), (10, 10)]),
        "3": Polygon([(20, 0), (30, 0), (30, 10), (20, 10)]),

        "4": Polygon([(0, 10), (10, 10), (10, 20), (0, 20)]),
        "5": Polygon([(10, 10), (20, 10), (20, 20), (10, 20)]),
        "6": Polygon([(20, 10), (30, 10), (30, 20), (20, 20)]),

        "7": Polygon([(0, 20), (10, 20), (10, 30), (0, 30)]),
        "8": Polygon([(10, 20), (20, 20), (20, 30), (10, 30)]),
        "9": Polygon([(20, 20), (30, 20), (30, 30), (20, 30)]),

        # Right-side room areas
        "10": Polygon([(40, 0), (30, 0), (30, 10), (40, 10), (40, 8)]),
        "11": Polygon([(40, 10), (30, 10), (30, 20), (40, 20)]),
        "12": Polygon([(40, 20), (30, 20), (30, 30), (40, 30)]),

        # Upper exit approach areas
        "13": Polygon([(21, 30), (15, 30), (15, 36), (21, 36)]),
        "14": Polygon([(25, 30), (21, 30), (21, 34), (25, 34)]),

        # Narrow right exit areas
        "15": Polygon([(42, 8), (40, 8), (40, 10), (42, 10)]),
        "16": Polygon([(44, 8), (42, 8), (42, 10), (44, 10)]),
        "17": Polygon([(46, 8), (44, 8), (44, 10), (46, 10)]),

        # Wide upper exit area
        "18": Polygon([(25, 34), (21, 34), (21, 36), (25, 36)]),
    }

    return Environment(
        name="two_exits",
        graph=G,
        complete_area=complete_area,
        obstacles=obstacles,
        waypoints=waypoints,
        sources=[],
        targets=[],
        specific_areas=specific_areas,
    )